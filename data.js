/* 検査の種類（施設の設定で日中・夜間の可否を切り替える） */
const TEST_KINDS = {s:'簡易検査（バイタル・SpO2・血糖・尿・導尿）', b:'血液検査', e:'12誘導心電図', x:'X線', c:'単純CT', o:'院内では困難（造影CT・エコー・血液ガスなど）'};
function testKind(t){
 if(/^(血糖|SpO2|尿検査|導尿|起立|両上肢|体重|直腸診|モニター)/.test(t))return 's';
 if(/造影|エコー|血液ガス|MRI|ホルター/.test(t))return 'o';
 if(/CT/.test(t))return 'c';
 if(/X線/.test(t))return 'x';
 if(/心電図/.test(t))return 'e';
 return 'b';
}
